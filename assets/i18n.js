  function bustLinks() {
    document.querySelectorAll('a[href]').forEach((a) => {
      const href = a.getAttribute('href');
      if (!href || href.startsWith('http') || href.startsWith('#') || href.startsWith('mailto:')) return;
      if (!/\.html(\?|$)/.test(href)) return;
      try {
        const url = new URL(href, location.href);
        url.searchParams.set('v', '8');
        const file = url.pathname.split('/').pop();
        a.setAttribute('href', file + '?' + url.searchParams.toString());
      } catch (_) {}
    });
  }

  function apply(lang) {
    const pack = dict[lang] || dict[DEFAULT];
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (pack[key] != null) el.textContent = pack[key];
    });
    document.querySelectorAll('.lang-btn').forEach((btn) => {
      btn.classList.toggle('active', btn.dataset.lang === lang);
      btn.setAttribute('aria-pressed', btn.dataset.lang === lang ? 'true' : 'false');
    });
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (_) {}
    window.__vitbApply = apply;
  }

  function init() {
    let lang = DEFAULT;
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved && dict[saved]) lang = saved;
    } catch (_) {}
    window.__vitbApply = apply;
    apply(lang);
    bustLinks();
    if ('IntersectionObserver' in window) {
      const io = new IntersectionObserver((es) => es.forEach((e) => { if (e.isIntersecting) { e.target.classList.add('in'); io.unobserve(e.target); } }), { threshold: 0.05, rootMargin: '0px 0px -40px 0px' });
      setTimeout(() => document.querySelectorAll('.reveal').forEach((el) => el.classList.add('in')), 1800);
      document.querySelectorAll('.reveal').forEach((el) => io.observe(el));
    } else {
      document.querySelectorAll('.reveal').forEach((el) => el.classList.add('in'));
    }
    document.addEventListener('click', (e) => {
      const btn = e.target.closest('.lang-btn');
      if (!btn) return;
      e.preventDefault();
      const next = btn.getAttribute('data-lang');
      if (next && dict[next]) apply(next);
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
